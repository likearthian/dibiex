func TestPostgreSQLTableDDL(t *testing.T) {
	table := PostgreSQLTable{Name: `Order "items`, Schema: "tenant", Owner: `role"owner`, Comment: "It's a \\ table", Columns: []PostgreSQLColumn{{Name: "id", Type: "bigint", PrimaryKey: true, Identity: "BY DEFAULT"}, {Name: "price", Type: "numeric(18,2)", Default: "0", NotNull: true}, {Name: "customer_id", Type: "uuid"}}, Constraints: []PostgreSQLConstraint{{Name: "positive_price", Kind: "CHECK", Expression: "price >= 0"}, {Kind: "FOREIGN KEY", Columns: "customer_id", ReferenceSchema: "public", ReferenceTable: "customer", ReferenceColumns: "id", OnDelete: "CASCADE"}}, Fillfactor: "85", Autovacuum: "true", RowSecurity: true, ForceRowSecurity: true}
	statements, err := table.Statements()
	if err != nil {
		t.Fatal(err)
	}
	ddl := strings.Join(statements, ";\n")
	for _, want := range []string{`CREATE TABLE "tenant"."Order ""items"`, `"id" bigint GENERATED BY DEFAULT AS IDENTITY`, `PRIMARY KEY ("id")`, `numeric(18,2) DEFAULT (0) NOT NULL`, `CONSTRAINT "positive_price" CHECK (price >= 0)`, `REFERENCES "public"."customer" ("id") ON DELETE CASCADE`, `WITH (fillfactor = 85, autovacuum_enabled = true)`, `IS E'It''s a \\ table'`, `FORCE ROW LEVEL SECURITY`, `OWNER TO "role""owner"`} {
		if !strings.Contains(ddl, want) {
			t.Fatalf("missing %s in %s", want, ddl)
		}
	}
	if !strings.Contains(statements[len(statements)-1], "OWNER TO") {
		t.Fatal("ownership must be changed last")
	}
}

func TestPostgreSQLTableValidation(t *testing.T) {
	valid := func() PostgreSQLTable {
		return PostgreSQLTable{Name: "events", Schema: "public", Columns: []PostgreSQLColumn{{Name: "id", Type: "bigint"}, {Name: "created_at", Type: "timestamp with time zone"}}}
	}
	cases := []struct {
		name   string
		change func(*PostgreSQLTable)
	}{
		{"missing name", func(d *PostgreSQLTable) { d.Name = "" }},
		{"long identifier", func(d *PostgreSQLTable) { d.Name = strings.Repeat("x", 64) }},
		{"no columns", func(d *PostgreSQLTable) { d.Columns = nil }},
		{"duplicate columns", func(d *PostgreSQLTable) { d.Columns[1].Name = "id" }},
		{"invalid type", func(d *PostgreSQLTable) { d.Columns[0].Type = "integer; DROP TABLE t" }},
		{"identity on text", func(d *PostgreSQLTable) { d.Columns[0].Type = "text"; d.Columns[0].Identity = "ALWAYS" }},
		{"identity and default", func(d *PostgreSQLTable) { d.Columns[0].Identity = "ALWAYS"; d.Columns[0].Default = "1" }},
		{"multiple statements", func(d *PostgreSQLTable) { d.Columns[0].Default = "1; SELECT 1" }},
		{"missing constraint column", func(d *PostgreSQLTable) { d.Constraints = []PostgreSQLConstraint{{Kind: "UNIQUE", Columns: "unknown"}} }},
		{"two primary keys", func(d *PostgreSQLTable) {
			d.Columns[0].PrimaryKey = true
			d.Constraints = []PostgreSQLConstraint{{Kind: "PRIMARY KEY", Columns: "created_at"}}
		}},
		{"invalid fillfactor", func(d *PostgreSQLTable) { d.Fillfactor = "101" }},
		{"force without enable", func(d *PostgreSQLTable) { d.ForceRowSecurity = true }},
		{"partition unique key", func(d *PostgreSQLTable) {
			d.Partitioned = true
			d.PartitionMethod = "RANGE"
			d.PartitionColumns = "created_at"
			d.Columns[0].PrimaryKey = true
		}},
		{"partition storage", func(d *PostgreSQLTable) {
			d.Partitioned = true
			d.PartitionMethod = "HASH"
			d.PartitionColumns = "id"
			d.Fillfactor = "80"
		}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			d := valid()
			tc.change(&d)
			if _, err := d.Statements(); err == nil {
				t.Fatal("invalid definition accepted")
			}
		})
	}
	d := valid()
	d.Partitioned = true
	d.PartitionMethod = "RANGE"
	d.PartitionColumns = "created_at"
	d.Columns[0].PrimaryKey = true
	d.Columns[1].PrimaryKey = true
	ddl, err := d.Statements()
	if err != nil || !strings.Contains(ddl[0], `PARTITION BY RANGE ("created_at")`) {
		t.Fatalf("valid partitioned composite key rejected: %v", err)
	}
	for _, typ := range []string{"integer[]", "numeric(12, 4)", "timestamp(6) without time zone", `"custom"."enum_type"`} {
		d := valid()
		d.Columns[0].Type = typ
		if _, err := d.Statements(); err != nil {
			t.Fatalf("valid type %s: %v", typ, err)
		}
	}
}

func TestCreatePostgreSQLTableIntegration(t *testing.T) {
	dsn := os.Getenv("DBCRAFT_TEST_POSTGRES_DSN")
	if dsn == "" {
		t.Skip("set DBCRAFT_TEST_POSTGRES_DSN to run live PostgreSQL DDL tests")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	db, err := sql.Open("pgx", dsn)
	if err != nil {
		t.Fatal("invalid PostgreSQL test connection")
	}
	defer db.Close()
	db.SetMaxOpenConns(1)
	client := &Client{db: db, config: Config{Engine: PostgreSQL}}
	name := "dbcraft_create_test_" + strconv.FormatInt(time.Now().UnixNano(), 10)
	_, err = db.ExecContext(ctx, "CREATE SCHEMA "+QuoteIdentifier(name))
	if err != nil {
		t.Fatal(err)
	}
	defer db.ExecContext(context.Background(), "DROP SCHEMA "+QuoteIdentifier(name)+" CASCADE")
	d := PostgreSQLTable{Name: "created", Schema: name, Columns: []PostgreSQLColumn{{Name: "id", Type: "bigint", Identity: "ALWAYS", PrimaryKey: true}}}
	if err = client.CreatePostgreSQLTable(ctx, d); err != nil {
		t.Fatal(err)
	}
	d.Name = "rollback_test"
	d.Owner = "dbcraft_nonexistent_owner_7b94f"
	if err = client.CreatePostgreSQLTable(ctx, d); err == nil {
		t.Fatal("missing role should fail")
	}
	var exists bool
	if err = db.QueryRowContext(ctx, "SELECT to_regclass($1) IS NOT NULL", name+".rollback_test").Scan(&exists); err != nil || exists {
		t.Fatalf("failed creation did not roll back: %v", err)
	}
	// An editor transaction lives on a pinned connection. Returning BEGIN to
	// database/sql's pool lets pgx discard it before the designer sees it.
	conn, err := db.Conn(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close()
	client.session = conn
	if _, err = conn.ExecContext(ctx, "BEGIN"); err != nil {
		t.Fatal(err)
	}
	defer conn.ExecContext(context.Background(), "ROLLBACK")
	d.Owner = ""
	d.Name = "blocked"
	if err = client.CreatePostgreSQLTable(ctx, d); err == nil {
		t.Fatal("designer must not commit an existing editor transaction")
	}
	if _, err = conn.ExecContext(ctx, "ROLLBACK"); err != nil {
		t.Fatal(err)
	}
}
